// lib/stub-generator.js — Generate compact stub SKILL.md that replaces the original.
//
// The stub preserves the original `name` (so Claude Code keeps the same
// callable id) but compresses `description` to a short hint + pointer to the
// vault backup. The agent reads the vault via Read tool when it actually
// wants to invoke the skill.

'use strict';

const { stringify } = require('./frontmatter');

const HINT_MAX = 80;
const STUB_MARKER = '[lazy]';

/**
 * Shorten a description to a routing hint. Truncates at word boundary
 * near HINT_MAX chars, adds ellipsis if truncated.
 */
function makeHint(description) {
  const str = String(description || '').trim();
  if (str.length <= HINT_MAX) return str;
  const slice = str.slice(0, HINT_MAX);
  const lastSpace = slice.lastIndexOf(' ');
  return (lastSpace > 30 ? slice.slice(0, lastSpace) : slice).trim() + '…';
}

/**
 * Build the stub description: `[lazy] <hint>. Vault: <vaultPath>`
 */
function makeStubDescription(hint, vaultPath) {
  const displayPath = vaultPath.replace(/^.*?\.claude/, '~/.claude');
  return `${STUB_MARKER} ${hint}. Vault: ${displayPath}`;
}

/**
 * Render the complete stub SKILL.md content.
 *
 * @param {object} opts
 * @param {string} opts.name            original skill name (preserved)
 * @param {string} opts.description     original description (will be shortened)
 * @param {string} opts.vaultPath       absolute path to vault backup
 * @param {string} [opts.bootstrappedAt] ISO date for the marker comment
 */
function renderStub(opts) {
  if (!opts || !opts.name) throw new Error('renderStub: name required');
  if (!opts.vaultPath) throw new Error('renderStub: vaultPath required');

  const hint = makeHint(opts.description || '');
  const stubDesc = makeStubDescription(hint, opts.vaultPath);
  const iso = opts.bootstrappedAt || new Date().toISOString();
  const displayPath = opts.vaultPath.replace(/^.*?\.claude/, '~/.claude');

  const fm = { name: opts.name, description: stubDesc };
  const body = [
    `<!-- stub generated by lazy-skill-loader at ${iso} -->`,
    `<!-- full content: ${displayPath} -->`,
    `<!-- use Read tool to load full instructions -->`,
    '',
    `# ${opts.name} (stub)`,
    '',
    `Full SKILL.md content has been moved to the lazy-skills vault to save context tokens.`,
    `Load it with:`,
    '',
    '```',
    `Read("${opts.vaultPath}")`,
    '```',
    '',
  ].join('\n');

  return stringify(fm, body);
}

/**
 * Detect whether a SKILL.md content is already a stub we generated.
 */
function isStub(content) {
  if (typeof content !== 'string') return false;
  // Check both frontmatter description marker and HTML comment marker
  return content.includes(STUB_MARKER) &&
         content.includes('stub generated by lazy-skill-loader');
}

module.exports = { renderStub, isStub, makeHint, makeStubDescription, HINT_MAX };
